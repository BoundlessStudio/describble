const wordOrders = [
  (subject, look) => `${subject}, ${look}`,
  (subject, look) => `${subject}, with ${look}`,
  (subject, look) => `${look}; ${subject}`,
  (subject, look) => `${subject} and ${look}`,
  (subject, look) => `${subject}. Add ${look}.`,
];

export const portraitIdeas = themes.flatMap(({ name, subjects, looks }) =>
  subjects.flatMap(([subject, ...primary], index) => looks.map(([look, ...secondary], variant) => {
    const expected = [...primary, ...secondary];
    const describe = expected.some((trait) => trait.startsWith('-')) ? wordOrders[0] : wordOrders[(index + variant) % wordOrders.length];
    return { theme: name, description: describe(subject, look), expected };
  })));
